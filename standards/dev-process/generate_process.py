"""Generate a repository's development-process harness from one spec.

The generic loop, evidence ladder, experiment card, playtest request and work classes live in
process.base.json (shared through dev-standards). A repository adds its own phases and class
gates in an overlay JSON file. This script merges the two and writes:

- the full process document (overlay "process_doc"),
- the merged spec the evidence check reads (overlay "merged_spec"),
- the experiment and playtest issue forms and the pull request template,
- a short summary between <!-- dev-process:begin --> and <!-- dev-process:end --> in the
  agent instruction file (overlay "agents_file").

The overlay sits next to this script (process.overlay.json) unless --overlay names another.

Usage (from the repository root, with the files vendored to e.g. scripts/process/):
    python scripts/process/generate_process.py            # write
    python scripts/process/generate_process.py --check    # exit 1 if any output drifted
Standard library only.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEGIN = "<!-- dev-process:begin (generated by {script}; edit the overlay) -->"
END = "<!-- dev-process:end -->"


def load(base_path: Path, overlay_path: Path) -> dict:
    """Merge the overlay into the base spec; overlay class keys extend, never drop, base gates."""
    base = json.loads(base_path.read_text(encoding="utf-8"))
    overlay = json.loads(overlay_path.read_text(encoding="utf-8"))
    spec = dict(base)
    spec["overlay"] = {k: v for k, v in overlay.items() if k != "classes"}
    classes = {k: dict(v) for k, v in base["classes"].items()}
    for key, extra in overlay.get("classes", {}).items():
        merged = classes.setdefault(key, {"title": key, "use": "", "gate": "", "min_rung": "", "sections": []})
        if extra.get("gate_extra"):
            merged["gate"] = (merged["gate"] + " " + extra["gate_extra"]).strip()
        if "min_rung" in extra:
            merged["min_rung"] = extra["min_rung"]
        for section in extra.get("sections_extra", []):
            if section not in merged["sections"]:
                merged["sections"].append(section)
        if extra.get("checks"):
            merged["checks"] = extra["checks"]
    spec["classes"] = classes
    spec["pr_checklist"] = base["pr_checklist"] + overlay.get("pr_checklist_extra", [])
    return spec


def phase_by_id(spec: dict) -> dict:
    """Return the current phase record; the overlay must name one of its phases."""
    ov = spec["overlay"]
    for phase in ov["phases"]:
        if phase["id"] == ov["current_phase"]:
            return phase
    raise SystemExit(f"current_phase {ov['current_phase']!r} is not in phases")


def render_doc(spec: dict) -> str:
    """The full process document agents read before planning work."""
    ov = spec["overlay"]
    cur = phase_by_id(spec)
    out = [
        f"# {ov['project']} development process",
        "",
        f"<!-- Generated by {ov['script_path']} from {ov['base_path']}",
        f"     and {ov['overlay_path']}. Edit those, then run the generator. -->",
        "",
        "Every piece of work runs the same loop, claims evidence on one ladder and belongs to one",
        "work class with its own gate. The phase decides which classes are open.",
        "",
        "## The loop",
        "",
    ]
    out += [f"{i}. **{s['step']}.** {s['text']}" for i, s in enumerate(spec["loop"], 1)]
    out += ["", "## Evidence ladder", "", "| Rung | Name | What it proves | Tools here |", "|---|---|---|---|"]
    tools = ov.get("ladder_tools", {})
    out += [f"| {r['rung']} | {r['name']} | {r['text']} | {tools.get(r['rung'], '')} |" for r in spec["ladder"]]
    out += [""] + [f"- {rule}" for rule in spec["ladder_rules"]]
    out += ["", "## Phases", "", f"Current phase: **{cur['title']}**. {ov.get('current_phase_note', '')}".rstrip(), ""]
    for phase in ov["phases"]:
        mark = " (current)" if phase["id"] == cur["id"] else ""
        out += [f"### {phase['title']}{mark}", "", f"- Entry: {phase['entry']}", f"- Exit: {phase['exit']}"]
        if phase.get("locks"):
            out.append(f"- Locks: {phase['locks']}")
        out.append("")
    out += ["## Work classes", "", "Put `Class: <key>` and `Rung: <E0-E4 or none>` at the top of every pull request.", "",
            "| Key | Class | Use for | Gate | Lowest rung |", "|---|---|---|---|---|"]
    for key, c in spec["classes"].items():
        out.append(f"| `{key}` | {c['title']} | {c['use']} | {c['gate']} | {c['min_rung'] or 'none'} |")
    out += ["", "## Experiment card", "", "Open an issue with the Experiment form. Fields:", ""]
    out += [f"- **{f['label']}**{'' if f['required'] else ' (after the run)'}: {f['help']}" for f in spec["card"]]
    out += [""] + [f"- {rule}" for rule in spec["card_rules"]]
    out += ["", "## Playtest request", "",
            "When a claim needs E3 or E4, open an issue with the Playtest form and stop that line of work",
            "until the results comment lands. Keep it to about 15 lines. Fields:", ""]
    out += [f"- **{f['label']}**: {f['help']}" for f in spec["playtest_request"]]
    out += ["", "## Pull request checklist", ""] + [f"- {item}" for item in spec["pr_checklist"]]
    out += ["", "## What CI checks", "",
            f"`{ov['check_command']}` reads the pull request body. It fails when the class is missing or",
            "unknown, the rung is below the class's lowest rung, a required section is empty, or an",
            "evidence line names no file that exists in the checkout and no link. It does not judge the",
            "evidence; the checking agent does.", ""]
    for extra in ov.get("doc_extra", []):
        out += [extra, ""]
    return "\n".join(out).rstrip() + "\n"


def render_agents_block(spec: dict) -> str:
    """The short always-loaded summary placed in the agent instruction file."""
    ov = spec["overlay"]
    cur = phase_by_id(spec)
    lines = [BEGIN.format(script=ov["script_path"]), "## Development process", "",
             f"Read `{ov['process_doc']}` before planning work. In short:", ""]
    lines.append("- Loop: " + " → ".join(s["step"] for s in spec["loop"]) +
                 ". Write the prediction and kill rule before any result, and commit them first.")
    lines.append("- Evidence ladder: " + "; ".join(f"{r['rung']} {r['name'].lower()}" for r in spec["ladder"]) +
                 ". Never claim a higher rung than you reached. Fun, feel and look need E3 or E4: open a"
                 " Playtest issue; the owner plays when asked.")
    lines.append(f"- Phase: **{cur['title']}**. {cur.get('locks', '')}".rstrip())
    lines.append("- Every pull request starts with `Class:` (" + ", ".join(f"`{k}`" for k in spec["classes"]) +
                 ") and `Rung:`. CI checks the class gate's sections and evidence lines.")
    lines += ["", END]
    return "\n".join(lines)


def render_issue_form(name: str, description: str, labels: list[str], fields: list[dict], intro: str) -> str:
    """A GitHub issue form; JSON strings are valid YAML scalars, so no YAML library is needed."""
    out = [f"name: {json.dumps(name)}", f"description: {json.dumps(description)}",
           f"labels: {json.dumps(labels)}", "body:",
           "  - type: markdown", "    attributes:", f"      value: {json.dumps(intro)}"]
    for f in fields:
        out += [
            "  - type: textarea", f"    id: {f['id']}", "    attributes:",
            f"      label: {json.dumps(f['label'])}", f"      description: {json.dumps(f['help'])}",
            "    validations:", f"      required: {'true' if f['required'] else 'false'}",
        ]
    return "\n".join(out) + "\n"


def render_pr_template(spec: dict) -> str:
    """The pull request body every agent fills; the evidence check parses it."""
    sections = []
    for c in spec["classes"].values():
        for s in c["sections"]:
            if s not in sections:
                sections.append(s)
    out = [
        "Class: <" + " | ".join(spec["classes"]) + ">",
        "Rung: <E0 | E1 | E2 | E3 | E4 | none>",
        "",
        f"<!-- {spec['overlay']['process_doc']} lists each class's gate. Sections a class does not need may be deleted. -->",
        "",
        "### Summary",
        "",
    ]
    for s in sections:
        hint = {
            "Card": "<!-- experiment: the card issue, e.g. #123 -->",
            "Evidence": "<!-- one line each: a file in this PR in backticks, or a link, then what it shows -->\n- `path/to/test_or_report` — what it shows",
            "Reached / not shown": "<!-- the rung reached, and what this evidence does not show -->",
            "Decision": "<!-- keep, revise, remove, inconclusive or investigate -->",
        }.get(s, "")
        out += [f"### {s}", "", hint, ""] if hint else [f"### {s}", ""]
    out += ["### Checklist", ""] + [f"- [ ] {item}" for item in spec["pr_checklist"]]
    return "\n".join(out) + "\n"


def splice(text: str, block: str) -> str:
    """Replace the marked block in the agent file; the markers must already exist once."""
    start = text.find("<!-- dev-process:begin")
    end = text.find(END)
    if start < 0 or end < 0 or text.count(END) != 1:
        raise SystemExit("agent file needs exactly one dev-process:begin/end marker pair")
    return text[:start] + block + text[end + len(END):]


def outputs(root: Path, spec: dict) -> dict[Path, str]:
    """Every generated file and its expected content."""
    ov = spec["overlay"]
    merged = {k: v for k, v in spec.items()}
    agents = root / ov["agents_file"]
    files = {
        root / ov["process_doc"]: render_doc(spec),
        root / ov["merged_spec"]: json.dumps(merged, indent=2, ensure_ascii=False) + "\n",
        root / ".github/ISSUE_TEMPLATE/experiment.yml": render_issue_form(
            "Experiment", "A hypothesis about play, with the prediction written before any result.",
            ["experiment"], spec["card"],
            "Fill Question to Method now and commit nothing else first. Result, Reached and Decision are filled after the run, as edits by the checking agent or as comments. Do not edit the Prediction after results exist."),
        root / ".github/ISSUE_TEMPLATE/playtest.yml": render_issue_form(
            "Playtest request", "Ask the owner to play a build to answer one or two observable questions.",
            ["playtest", "needs-owner"], spec["playtest_request"],
            "Keep it to about 15 lines. Write the decision rule before the owner plays."),
        root / ".github/pull_request_template.md": render_pr_template(spec),
    }
    current = agents.read_text(encoding="utf-8") if agents.exists() else ""
    files[agents] = splice(current, render_agents_block(spec))
    return files


def rel(path: Path, root: Path) -> str:
    """A path relative to the repository root when inside it, else its absolute form (for messages)."""
    path = path.resolve()
    return path.relative_to(root).as_posix() if path.is_relative_to(root) else path.as_posix()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path.cwd())
    parser.add_argument("--base", type=Path, default=HERE / "process.base.json")
    parser.add_argument("--overlay", type=Path, default=HERE / "process.overlay.json")
    parser.add_argument("--check", action="store_true", help="report drift and exit 1 instead of writing")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    spec = load(args.base, args.overlay)
    for key, path in (("overlay_path", args.overlay), ("base_path", args.base), ("script_path", Path(__file__))):
        spec["overlay"][key] = rel(path, root)
    drift = []
    for path, content in outputs(root, spec).items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == content:
            continue
        if args.check:
            drift.append(path.relative_to(root).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode("utf-8"))
            print(f"wrote {path.relative_to(root).as_posix()}")
    if drift:
        print(f"PROCESS_DRIFT: regenerate with python {spec['overlay']['script_path']}:", *drift, sep="\n  ")
        return 1
    if args.check:
        print("PROCESS_OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
